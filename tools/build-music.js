/* The soundtrack for the pages (js/music.js):
 *   node tools/build-music.js                       wraps every media/music/<song>.mp3 as media/music/<song>.js
 *                                                   (base64 in a classic script, so it loads from file:// too)
 *   node tools/build-music.js --analyze <song> [--range a0,a1,b0,b1] [--chrome <chrome.exe>]
 *                                                   measures a song in headless Chrome and suggests its entry for
 *                                                   SONGS in js/music.js: the loudness trim to -16 LUFS and a loop
 *                                                   splice; writes a picture of the splice to tools/out/music-<song>.jpg
 *
 * The loop: the song leaves at A (late in the song) and goes on from B (early), where the 6 s before each
 * point have the same rhythm (onsets in four bands, at 10 ms) and much the same sound (band energies).
 * A is searched over a0..a1 (default the last 25 s but 3) and B over b0..b1 (default 3 s to A - 45 s).
 * The pair is refined below 10 ms, then the splice is moved to 25 ms before a drum hit both places
 * share, with B shifted so the two hits line up to the millisecond. The picture shows the song straight
 * through at A, the spliced result and the song at B, lined up at the splice: drum hits should make
 * unbroken vertical stripes, and the onset traces (red at A, green at B) should peak together before it.
 * The tempo of these songs isn't a clean grid, so look at the picture before taking the numbers. */
