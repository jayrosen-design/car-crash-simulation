/* Builds the two single-file pages, so they work in any viewer, including ones that can't load
 * sibling files (preview panes, or a file copied on its own):
 *   Simulator.html             index.html with the stylesheet and every local script embedded
 *                              (three.js still comes from the CDN, so it needs an internet connection)
 *   Car Crash Simulation.html  home.html with its pictures and video (media/) embedded
 *   node tools/build-standalone.js
 * Edit the sources (index.html, home.html, css/, js/, models/, media/) and rebuild; don't edit the
 * output. */
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const safe = (code) => code.replace(/<\/(script)/gi, '<\\/$1');   // can't end the inline tag early
let html = read('index.html');

let n = 0;
html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (_, href) => { n++; return `<style>/* ${href} */\n${read(href)}\n</style>`; });
html = html.replace(/<script src="([^"]+)"><\/script>/g, (_, src) => { n++; return `<script>/* ${src} */\n${safe(read(src))}\n</script>`; });
const list = html.match(/const APP_SCRIPTS = (\[[^\]]*\]);/);
if (!list) throw new Error('APP_SCRIPTS list not found in index.html');
const appScripts = JSON.parse(list[1].replace(/'/g, '"'));
const blocks = appScripts.map((src) => { n++; return `<script type="text/x-inline" data-src="${src}">\n${safe(read(src))}\n</script>`; }).join('\n');
// function replacers only: a string replacement would treat "$$", "$'" etc. in the code as patterns
html = html.replace('<script type="module">', () => `${blocks}\n<script type="module">`);
html = html.replace('<!doctype html>', () => '<!doctype html>\n<!-- Generated by tools/build-standalone.js from index.html, css/ and js/. Edit those and rebuild. -->');

// every embedded file must appear verbatim
for (const f of ['css/style.css', ...[...read('index.html').matchAll(/<script src="([^"]+)">/g)].map(m => m[1]), ...appScripts]) {
  const body = f.endsWith('.css') ? read(f) : safe(read(f));
  if (!html.includes(body)) throw new Error(`${f} was not embedded intact`);
}

const out = path.join(root, 'Simulator.html');
fs.writeFileSync(out, html);
console.log(`wrote ${path.relative(root, out)}: ${n} files embedded, ${(html.length / 1024).toFixed(0)} KB`);

// ---------------------------------------------------------------- the home page
// Pictures become data URIs; the video goes in a base64 script block that home.html's own script
// turns into a blob URL.
const b64 = (p) => fs.readFileSync(path.join(root, p)).toString('base64');
const homeSrc = read('home.html');
let home = homeSrc, nMedia = 0;
home = home.replace(/(src|poster)="(media\/[^"]+\.(jpg|png))"/g, (_, attr, p, ext) => { nMedia++; return `${attr}="data:image/${ext === 'jpg' ? 'jpeg' : ext};base64,${b64(p)}"`; });
const reel = home.match(/<video id="reel" src="(media\/[^"]+\.mp4)"/);
if (!reel) throw new Error('the reel video was not found in home.html');
home = home.replace(` src="${reel[1]}"`, () => '');
if (home.split('<script>').length !== 2) throw new Error('home.html should have exactly one <script> block');
home = home.replace('<script>', () => `<script type="text/x-base64" id="reel-data">${b64(reel[1])}</script>\n<script>`);
nMedia++;
home = home.replace('<!doctype html>', () => '<!doctype html>\n<!-- Generated by tools/build-standalone.js from home.html and media/. Edit those and rebuild. -->');
for (const m of homeSrc.matchAll(/(?:src|poster)="(media\/[^"]+)"/g)) {
  if (!home.includes(b64(m[1]))) throw new Error(`${m[1]} was not embedded intact`);
}
if (/(src|poster)="media\//.test(home)) throw new Error('home page still points at media/');
const homeOut = path.join(root, 'Car Crash Simulation.html');
fs.writeFileSync(homeOut, home);
console.log(`wrote ${path.relative(root, homeOut)}: ${nMedia} media files embedded, ${(home.length / 1048576).toFixed(1)} MB`);
