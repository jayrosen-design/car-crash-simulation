/* Builds the single-file pages, so they work in any viewer, including ones that can't load sibling
 * files (preview panes, or a file copied on its own):
 *   Simulator.html             index.html with the stylesheet and every local script embedded
 *   Race.html                  game.html (the Race game) the same way, with its photo textures
 *   Destruction.html           junction.html (the Destruction mode) the same way
 *   HurricaneBrawl.html        globe.html (the Hurricane Brawl game) the same way, with its Earth data
 *                              (three.js still comes from the CDN for these, so they need an internet
 *                              connection)
 *   Car Crash Simulation.html  home.html with its stylesheet, pictures and videos (css/, media/)
 *                              embedded (physics.html and sources.html are built by build-site.js)
 *   node tools/build-standalone.js           all of them
 *   node tools/build-standalone.js Race      only the ones whose file name contains "Race"
 * Edit the sources (index.html, game.html, junction.html, globe.html, home.html, css/, js/, models/, media/) and rebuild; don't
 * edit the output. */
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const safe = (code) => code.replace(/<\/(script)/gi, '<\\/$1');   // can't end the inline tag early

// a page with its stylesheets, scripts and APP_SCRIPTS (loaded by its module) embedded
function buildPage(source, output) {
  const src = read(source);
  let html = src, n = 0;
  html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (_, href) => { n++; return `<style>/* ${href} */\n${read(href)}\n</style>`; });
  html = html.replace(/<script src="([^"]+)"><\/script>/g, (_, src) => { n++; return `<script>/* ${src} */\n${safe(read(src))}\n</script>`; });
  const list = html.match(/const APP_SCRIPTS = (\[[^\]]*\]);/);
  if (!list) throw new Error(`APP_SCRIPTS list not found in ${source}`);
  const appScripts = JSON.parse(list[1].replace(/'/g, '"'));
  const blocks = appScripts.map((src) => { n++; return `<script type="text/x-inline" data-src="${src}">\n${safe(read(src))}\n</script>`; }).join('\n');
  // function replacers only: a string replacement would treat "$$", "$'" etc. in the code as patterns
  html = html.replace('<script type="module">', () => `${blocks}\n<script type="module">`);
  html = html.replace('<!doctype html>', () => `<!doctype html>\n<!-- Generated by tools/build-standalone.js from ${source}, css/ and js/. Edit those and rebuild. -->`);

  // every embedded file must appear verbatim
  const sheets = [...src.matchAll(/<link rel="stylesheet" href="([^"]+)">/g)].map(m => m[1]);
  const scripts = [...src.matchAll(/<script src="([^"]+)">/g)].map(m => m[1]);
  for (const f of [...sheets, ...scripts, ...appScripts]) {
    const body = f.endsWith('.css') ? read(f) : safe(read(f));
    if (!html.includes(body)) throw new Error(`${f} was not embedded intact`);
  }

  const out = path.join(root, output);
  fs.writeFileSync(out, html);
  console.log(`wrote ${path.relative(root, out)}: ${n} files embedded, ${(html.length / 1024).toFixed(0)} KB`);
}
const only = process.argv[2];
const wanted = (output) => !only || output.includes(only);
if (wanted('Simulator.html')) buildPage('index.html', 'Simulator.html');
if (wanted('Race.html')) buildPage('game.html', 'Race.html');
if (wanted('Destruction.html')) buildPage('junction.html', 'Destruction.html');
if (wanted('HurricaneBrawl.html')) buildPage('globe.html', 'HurricaneBrawl.html');
if (!wanted('Car Crash Simulation.html')) process.exit(0);

// ---------------------------------------------------------------- the home page
// The local stylesheet goes inline; pictures become data URIs; each video goes in a base64 script
// block (id "<video id>-data") that home.html's own script turns into a blob URL.
const b64 = (p) => fs.readFileSync(path.join(root, p)).toString('base64');
const homeSrc = read('home.html');
let home = homeSrc, nMedia = 0;
home = home.replace(/<link rel="stylesheet" href="(css\/[^"]+)">/g, (_, href) => { nMedia++; return `<style>/* ${href} */\n${read(href)}\n</style>`; });
home = home.replace(/(src|poster)="(media\/[^"]+\.(jpg|png))"/g, (_, attr, p, ext) => { nMedia++; return `${attr}="data:image/${ext === 'jpg' ? 'jpeg' : ext};base64,${b64(p)}"`; });
// the phone (9:16) cuts stay out of the single file: it plays the 16:9 ones everywhere
home = home.replace(/\s+data-portrait(?:-poster)?="media\/[^"]+"/g, '');
const videos = [...home.matchAll(/<video id="([^"]+)" src="(media\/[^"]+\.mp4)"/g)];
if (!videos.length) throw new Error('no video found in home.html');
for (const [, , src] of videos) { home = home.replace(` src="${src}"`, () => ''); nMedia++; }
if (home.split('<script>').length !== 2) throw new Error('home.html should have exactly one <script> block');
home = home.replace('<script>', () => videos.map(([, id, src]) => `<script type="text/x-base64" id="${id}-data">${b64(src)}</script>\n`).join('') + '<script>');
home = home.replace('<!doctype html>', () => '<!doctype html>\n<!-- Generated by tools/build-standalone.js from home.html, css/ and media/. Edit those and rebuild. -->');
for (const m of homeSrc.matchAll(/<link rel="stylesheet" href="(css\/[^"]+)">/g)) {
  if (!home.includes(read(m[1]))) throw new Error(`${m[1]} was not embedded intact`);
}
for (const m of homeSrc.matchAll(/ (?:src|poster)="(media\/[^"]+)"/g)) {
  if (!home.includes(b64(m[1]))) throw new Error(`${m[1]} was not embedded intact`);
}
if (/(src|poster)="media\//.test(home)) throw new Error('home page still points at media/');
const homeOut = path.join(root, 'Car Crash Simulation.html');
fs.writeFileSync(homeOut, home);
console.log(`wrote ${path.relative(root, homeOut)}: ${nMedia} media files embedded, ${(home.length / 1048576).toFixed(1)} MB`);
